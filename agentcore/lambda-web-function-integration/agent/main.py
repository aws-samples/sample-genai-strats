from bedrock_agentcore.runtime import BedrockAgentCoreApp
from strands import Agent
from strands.models import BedrockModel
from strands.types.exceptions import MaxTokensReachedException
import logging
import os

logging.basicConfig(level=logging.INFO)
l = logging.getLogger("main")
app = BedrockAgentCoreApp()

model_id = os.environ.get("MODEL_ID", "us.anthropic.claude-haiku-5-5")
l.info(f"model_id={model_id}")
model = BedrockModel(model_id=model_id, max_tokens=200)

def _message_text(message):
    """Concatenate the text blocks of a model message."""
    return "".join(block["text"] for block in (message or {}).get("content", []) if "text" in block)

@app.entrypoint
async def app_entrypoint(request_payload, context):
    l.info(f"> app_entrypoint")

    l.info(f"request_payload={request_payload}")

    prompt = request_payload.get("prompt")
    if not prompt:
        l.error("Request payload is missing required field: 'prompt'")
        yield {"type": "error", "error": "Missing required field: 'prompt'"}
        return

    # Gradually stream the agent's response as it is generated by the LLM. If the model hits its
    # output token cap, Strands raises MaxTokensReachedException right after yielding the assembled
    # message event. Track both the streamed deltas and that message, so on truncation we can emit
    # whatever text wasn't already streamed and then flag it.
    agent = Agent(model=model)
    streamed = ""
    partial = ""
    try:
        async for event in agent.stream_async(prompt=prompt):
            if "data" in event:
                streamed += event["data"]
                yield {"type": "chunk", "data": event["data"]}
            elif "message" in event:
                partial = _message_text(event["message"])
    except MaxTokensReachedException:
        l.warning("model response truncated: max_tokens reached")
        remainder = partial[len(streamed):] if partial.startswith(streamed) else partial
        if remainder:
            yield {"type": "chunk", "data": remainder}
        yield {"type": "chunk", "data": "\n\n(RESPONSE TOKEN LIMIT REACHED)"}

    l.info("< app_entrypoint (stream complete)")

if __name__ == "__main__":
    l.info("> main")

    # for key, value in sorted(os.environ.items()):
    #     l.info(f"env_var: {key}={value}")

    app.run(host="0.0.0.0", port=8080)
