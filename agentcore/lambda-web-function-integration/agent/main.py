from bedrock_agentcore.runtime import BedrockAgentCoreApp
from strands import Agent
from strands.models import BedrockModel
import logging
import os

logging.basicConfig(level=logging.INFO)
l = logging.getLogger("main")
app = BedrockAgentCoreApp()

model_id = os.environ.get("MODEL_ID", "us.anthropic.claude-sonnet-5-5")
l.info(f"model_id={model_id}")
model = BedrockModel(model_id=model_id)

@app.entrypoint
async def app_entrypoint(request_payload, context):
    l.info(f"> app_entrypoint")
    
    request_headers = dict(context.request.headers)
    l.info(f"request_payload={request_payload}")
    l.info(f"request_headers={request_headers}")

    prompt = request_payload.get("prompt")
    if not prompt:
        l.error("Request payload is missing required field: 'prompt'")
        yield {"type": "error", "error": "Missing required field: 'prompt'"}
        return

    # Immediately stream back the request metadata before the LLM is invoked.
    yield {
        "type": "request_metadata",
        "request_headers": request_headers,
        "request_payload": request_payload,
    }

    # Gradually stream the agent's response as it is generated by the LLM.
    agent = Agent(model=model)
    async for event in agent.stream_async(prompt=prompt):
        if "data" in event:
            yield {"type": "chunk", "data": event["data"]}

    l.info("< app_entrypoint (stream complete)")

if __name__ == "__main__":
    l.info("> main")

    # for key, value in sorted(os.environ.items()):
    #     l.info(f"env_var: {key}={value}")

    app.run(host="0.0.0.0", port=8080)
